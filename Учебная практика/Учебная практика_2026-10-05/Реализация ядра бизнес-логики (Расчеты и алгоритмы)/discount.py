"""Накопительная скидка партнера по общему количеству проданного товара.

Автор: Danis Arslanov

Количество считается в базе (SUM по истории продаж, см. db.py), сюда
приходит готовое число.
"""

# Нижняя граница количества (включительно) и скидка, которая с нее начинается.
# Границы идут по убыванию: первая, до которой количество дотянулось, и дает ответ.
DISCOUNT_TIERS = (
    (300_000, 15),
    (50_000, 10),
    (10_000, 5),
)


def calculate_discount(total_quantity: int) -> int:
    """Скидка в процентах: до 10 000 шт. - 0%, до 50 000 - 5%, до 300 000 - 10%,
    от 300 000 - 15%."""
    if total_quantity < 0:
        raise ValueError(f"Количество проданного товара не может быть отрицательным: {total_quantity}")
    for threshold, discount in DISCOUNT_TIERS:
        if total_quantity >= threshold:
            return discount
    return 0
